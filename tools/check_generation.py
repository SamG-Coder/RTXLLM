"""Compare the chunked E4 generator with per-byte host sampling on the same scene."""

import argparse
from pathlib import Path
from time import perf_counter

import byte_model as model
import numpy as np


def reference(scene, kernel, previous, count, rng):
    programs = np.column_stack(
        (np.full(32, 32, np.int32), np.arange(32, dtype=np.int32))
    )
    sampled = bytearray()
    for _ in range(count):
        paths, _ = scene.trace(
            kernel,
            {"start": np.full(32, 256 + previous, np.int32), "program": programs},
        )
        p = model.learn.vote_distribution(paths[:, 1][None, :])[0]
        previous = int(rng.choice(256, p=p))
        sampled.append(previous)
    return sampled


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("scene", type=Path)
    args = parser.parse_args()
    start = perf_counter()
    device, new = model.learn.bigram.open_kernel("generate.slang")
    data = model.read_geometry(args.scene)
    scene = model.learn.bigram.SpecularScene(device, data)
    model.sample_bytes(device, new, scene, 101, 1, np.random.default_rng(0))
    print(
        "Device creation, shader load, scene build and first byte, ms:",
        (perf_counter() - start) * 1000,
    )
    old = device.create_compute_kernel(device.load_program("specular.slang", ["trace"]))

    def run_old(n, seed):
        return reference(scene, old, 101, n, np.random.default_rng(seed))

    def run_new(n, seed):
        return model.sample_bytes(
            device, new, scene, 101, n, np.random.default_rng(seed)
        )

    for n, seed in ((0, 0), (1, 1), (255, 2), (256, 1), (257, 0), (513, 2)):
        assert run_old(n, seed) == run_new(n, seed), (n, seed)
    times = {"host": [], "chunked": []}
    for i in range(5):
        outputs = []
        methods = [("host", run_old), ("chunked", run_new)]
        for name, method in methods if i % 2 == 0 else reversed(methods):
            start = perf_counter()
            outputs.append(method(512, i))
            times[name].append((perf_counter() - start) * 1000)
        assert outputs[0] == outputs[1]
    print("512 generated bytes, wall ms:", times)
    print(
        "Median wall time ratio:",
        np.median(times["host"]) / np.median(times["chunked"]),
    )
    broken = data["tri_vertices"].copy()
    broken[data["tri_kind"] == 1, :, 0] += 10000
    scene.refit_vertices(broken)
    try:
        run_new(257, 0)
    except ValueError as exc:
        assert "failed to reach" in str(exc)
    else:
        raise AssertionError("Malformed ray path must fail")
    print("Boundary, seed and malformed geometry checks passed")


if __name__ == "__main__":
    main()
